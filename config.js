// フッターのバージョン表示を埋める。
// config.js はすべての画面で読み込まれているので、ここに置けば1箇所で済む。
(function () {
    function applyVersionLabel() {
        const conf = window.SHIFT_CONFIG || {};
        if (!conf.APP_VERSION) return;
        const updated = String(conf.APP_UPDATED || '');
        const m = updated.match(/^(\d{4})-(\d{2})-(\d{2})$/);
        const updatedText = m ? `${Number(m[2])}月${Number(m[3])}日 更新` : updated;
        const text = updatedText
            ? `バージョン ${conf.APP_VERSION}（${updatedText}）`
            : `バージョン ${conf.APP_VERSION}`;
        document.querySelectorAll('.app-version').forEach(el => { el.textContent = text; });
    }
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', applyVersionLabel);
    } else {
        applyVersionLabel();
    }
})();
